import assert from 'node:assert/strict';
import {googleLoginURL,finishGoogleLogin,clearGoogleLogin,cleanAuthURL} from '../pwa/google-auth.js';
const entries=new Map();
const storage={getItem:key=>entries.get(key)??null,setItem:(key,value)=>entries.set(key,value),removeItem:key=>entries.delete(key)};
const config={supabase_url:'https://auth.example.com'};
const callback='https://mobile.example.com/';
const url=new URL(await googleLoginURL(config,callback+'#leads',storage));
assert.equal(url.origin,config.supabase_url);
assert.equal(url.pathname,'/auth/v1/authorize');
assert.equal(url.searchParams.get('provider'),'google');
assert.equal(url.searchParams.get('redirect_to'),callback);
assert.equal(url.searchParams.get('code_challenge_method'),'s256');
assert.match(url.searchParams.get('code_challenge'),/^[A-Za-z0-9_-]{43}$/);
assert.equal(url.searchParams.has('code_verifier'),false);
let exchanges=0;
const auth=async(path,payload)=>{exchanges++;assert.equal(path,'token?grant_type=pkce');assert.equal(payload.auth_code,'good');assert.match(payload.code_verifier,/^[A-Za-z0-9_-]{43}$/);return {access_token:'token',refresh_token:'refresh',expires_in:3600,user:{id:'owner'},provider_token:'never-store'};};
assert.equal(await finishGoogleLogin(config,callback,auth,storage),null);
const result=await finishGoogleLogin(config,callback+'?code=good',auth,storage);
assert.equal(result.user.id,'owner');assert.equal(result.provider_token,undefined);
await assert.rejects(finishGoogleLogin(config,callback+'?code=good',auth,storage),/expired/);
assert.equal(exchanges,1);
await googleLoginURL(config,callback,storage);
await assert.rejects(finishGoogleLogin(config,'https://other.example.com/?code=good',auth,storage),/expired/);
await googleLoginURL(config,callback,storage);
const [key,pending]=[...entries][0];storage.setItem(key,JSON.stringify({...JSON.parse(pending),created:Date.now()-610000}));
await assert.rejects(finishGoogleLogin(config,callback+'?code=good',auth,storage),/expired/);
await googleLoginURL(config,callback,storage);
await assert.rejects(finishGoogleLogin({supabase_url:'https://other-auth.example.com'},callback+'?code=good',auth,storage),/expired/);
await googleLoginURL(config,callback,storage);
await assert.rejects(finishGoogleLogin(config,callback+'?error=access_denied',auth,storage),/complete nahi/);
assert.equal(entries.size,0);
await assert.rejects(googleLoginURL(config,'http://public.example.com/',storage),/HTTPS/);
assert.equal(cleanAuthURL(callback+'?code=secret&keep=yes#more'),'/?keep=yes#more');
assert.equal(cleanAuthURL(callback+'#access_token=secret&refresh_token=secret'),'/');
clearGoogleLogin(storage);
assert.equal(exchanges,1);
console.log('PASS: PKCE challenge, callback ownership/project/expiry, replay/cancel rejection, token minimization and URL cleanup');
