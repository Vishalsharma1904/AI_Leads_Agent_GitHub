param([switch]$Apply)
$ErrorActionPreference = 'Stop'
$workspaceRoot = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..')).TrimEnd('\')
$auditFolder = Join-Path $workspaceRoot 'work/cleanup-recovery-20261012'
$preservationPath = Join-Path $auditFolder 'preservation.json'
if (!(Test-Path -LiteralPath $preservationPath)) { throw 'Run prepare-size-cleanup.py successfully first.' }
$preserved = Get-Content -LiteralPath $preservationPath -Raw | ConvertFrom-Json
if (!(Test-Path -LiteralPath (Join-Path $workspaceRoot $preserved.resource_recovery_archive))) { throw 'Recovery archive missing.' }
if ($preserved.extracted_export_files_verified -lt 1) { throw 'Original export was not verified.' }

# Only known reproducible build output and a verified extracted export are listed.
# Application source, node_modules, databases, keys, installers and exports are excluded.
$relativeTargets = @(
 'Rudra24Mobile/.toolchain/gradle-cache',
 'Rudra24Mobile/.toolchain/jdk-17.0.20.1+1',
 'Rudra24Mobile/.toolchain/gradle-8.11.1',
 'Rudra24Mobile/.toolchain/jdk17.zip',
 'Rudra24Mobile/.toolchain/gradle.zip',
 'Rudra24Mobile/.toolchain/gradle-direct.zip',
 'Rudra24Mobile/.toolchain/gradle-fast.zip',
 'Rudra24Mobile/.toolchain/android-tools.zip',
 'Rudra24Mobile/.toolchain/android-tools-clean.zip',
 'Rudra24Mobile/.toolchain/android-tools',
 'Rudra24Mobile/.toolchain/android-tools-clean',
 'Rudra24Mobile/.toolchain/sdk/cmdline-tools',
 'Rudra24Mobile/.toolchain/sdk/build-tools',
 'Rudra24Mobile/.toolchain/sdk/platforms',
 'Rudra24Mobile/android/app/build',
 'Rudra24Mobile/android/.gradle',
 'release/win-unpacked',
 'tests/artifacts/package-verification/win-unpacked',
 'tests/artifacts/family-runtime/runtime',
 'work/dad-package-runtime'
)
$plans = @()
foreach ($relative in $relativeTargets) {
 $absolute = [IO.Path]::GetFullPath((Join-Path $workspaceRoot $relative))
 if (!$absolute.StartsWith($workspaceRoot+'\',[StringComparison]::OrdinalIgnoreCase)) { throw "Target outside workspace: $absolute" }
 if (!(Test-Path -LiteralPath $absolute)) { continue }
 $resolved = (Resolve-Path -LiteralPath $absolute).ProviderPath
 if (!$resolved.StartsWith($workspaceRoot+'\',[StringComparison]::OrdinalIgnoreCase)) { throw "Resolved target outside workspace: $resolved" }
 $rootItem = Get-Item -LiteralPath $resolved -Force
 if ($rootItem.Attributes -band [IO.FileAttributes]::ReparsePoint) { throw "Refusing reparse target: $resolved" }
 $tracked = & git -C $workspaceRoot ls-files -- $relative
 if ($LASTEXITCODE -ne 0 -or $tracked) { throw "Target contains tracked source: $relative" }
 $entries = @($rootItem)
 if ($rootItem.PSIsContainer) { $entries += @(Get-ChildItem -LiteralPath $resolved -Recurse -Force) }
 foreach ($entry in $entries) {
  if ($entry.Attributes -band [IO.FileAttributes]::ReparsePoint) { throw "Refusing nested reparse point: $($entry.FullName)" }
  if (!$entry.PSIsContainer -and ($entry.Name -like '.env*' -or $entry.Name -eq '.family-providers.json' -or $entry.Extension -in @('.db','.sqlite','.sqlite3','.jks','.keystore'))) { throw "Protected data found in cleanup target: $($entry.FullName)" }
 }
 $bytes = ($entries | Where-Object { !$_.PSIsContainer } | Measure-Object -Property Length -Sum).Sum
 $plans += [pscustomobject]@{ Relative=$relative; Absolute=$resolved; Bytes=[long]$bytes; Files=@($entries | Where-Object { !$_.PSIsContainer }).Count }
}
$plans | ConvertTo-Json -Depth 3 | Set-Content -LiteralPath (Join-Path $auditFolder 'cleanup-plan.json') -Encoding utf8
$plans | Select-Object Relative,Bytes,Files | Format-Table -AutoSize
Write-Output ('Verified generated bytes: '+(($plans | Measure-Object Bytes -Sum).Sum))
if (!$Apply) { Write-Output 'Audit only; nothing removed. Use -Apply to execute this exact allowlist.'; exit 0 }

foreach ($plan in $plans) {
 # A final absolute-path check immediately precedes every recursive deletion.
 $deletePath = (Resolve-Path -LiteralPath $plan.Absolute).ProviderPath
 if (!$deletePath.StartsWith($workspaceRoot+'\',[StringComparison]::OrdinalIgnoreCase)) { throw 'Deletion target escaped workspace.' }
 Remove-Item -LiteralPath $deletePath -Recurse -Force
 Write-Output ('Removed generated output: '+$plan.Relative)
}
foreach ($property in $preserved.protected_hashes.PSObject.Properties) {
 $sourcePath = Join-Path $workspaceRoot $property.Name
 if ((Get-FileHash -LiteralPath $sourcePath -Algorithm SHA256).Hash.ToLowerInvariant() -ne $property.Value) { throw "Protected file changed: $($property.Name)" }
}
Write-Output 'Protected source and final APK hashes unchanged.'
