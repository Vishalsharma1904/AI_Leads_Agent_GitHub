#!/usr/bin/env bash
# Builds Windows/CPython 3.12 backend packages (any OS, needs uv) for:
#   python scripts/build-share-zip.py --family ... --site-packages <out>
set -euo pipefail
OUT="${1:-work/win-site-packages}"
REQ="$(mktemp)"
grep -v -E '^(torch|kokoro|faster-whisper|silero-vad|onnxruntime)' backend/requirements.txt > "$REQ"
echo cryptography >> "$REQ"
uv pip compile "$REQ" --python-version 3.12 --python-platform x86_64-pc-windows-msvc -q -o "$REQ.lock"
rm -rf "$OUT"
uv pip install -r "$REQ.lock" --target "$OUT" --python-version 3.12 --python-platform x86_64-pc-windows-msvc --no-deps -q
echo "site-packages ready: $OUT"
